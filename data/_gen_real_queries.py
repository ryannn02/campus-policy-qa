def main() -> None:
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["question", "category", "frequency"])
        w.writeheader()
        for q, c, fr in ROWS:
            w.writerow({"question": q, "category": c, "frequency": fr})
    print(f"已生成 {OUT}，共 {len(ROWS)} 条")
    from collections import Counter
    cat = Counter(c for _, c, _ in ROWS)
    for k, v in cat.most_common():
        print(f"  {k}: {v} ({v/len(ROWS)*100:.1f}%)")


if __name__ == "__main__":
    main()
